#!/usr/bin/env python3
"""Generates the tables of src/generated/ from the PHP sources.

    python3 rust/crates/phab-remarkup/data/generate.py

Run from anywhere; it finds the repository root from its own path.
"""

import glob
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "../../../.."))
OUT = os.path.join(HERE, "../src/generated")


def php_sources():
    for base in ("src", "moz-extensions"):
        yield from glob.glob(os.path.join(ROOT, base, "**/*.php"), recursive=True)


def read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as handle:
        return handle.read()


def php_string(literal):
    """Decodes a PHP double-quoted string made of \\xNN escapes and ASCII."""
    out = bytearray()
    index = 0
    while index < len(literal):
        if literal.startswith("\\x", index):
            out.append(int(literal[index + 2 : index + 4], 16))
            index += 4
        else:
            out.extend(literal[index].encode())
            index += 1
    return bytes(out)


def rust_bytes(value):
    return 'b"' + "".join(
        chr(b) if 0x20 <= b < 0x7F and chr(b) not in '"\\' else "\\x%02x" % b
        for b in value
    ) + '"'


def array_body(source, function):
    match = re.search(
        r"function " + function + r"\(\) \{\s*return array\((.*?)\);", source, re.S
    )
    return match.group(1)


def write(name, doc, body):
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as handle:
        handle.write("// Generated by data/generate.py from the PHP sources: do not edit.\n\n")
        handle.write(doc)
        handle.write(body)


def emoji():
    source = read("src/applications/remarkup/markup/PhabricatorEmojiRemarkupRule.php")
    entries = re.findall(r"'([^']+)' => \"([^\"]*)\",", source)
    lines = "".join(
        "    (b\"%s\", %s),\n" % (name, rust_bytes(php_string(value)))
        # Later keys win, as in a PHP array.
        for name, value in sorted(dict(entries).items())
    )
    write(
        "emoji.rs",
        "/// `PhabricatorEmojiRemarkupRule`'s map, sorted by name.\n",
        "pub static EMOJI: &[(&[u8], &[u8])] = &[\n" + lines + "];\n",
    )


def icons():
    source = read("src/view/phui/PHUIIconView.php")
    names = re.findall(r"'([^']+)'", array_body(source, "getIcons"))
    colors = re.findall(r"'([^']+)'", array_body(source, "getIconColors"))
    body = "pub static ICONS: &[&str] = &[\n"
    body += "".join('    "%s",\n' % name for name in sorted(set(names)))
    body += "];\n\n/// `PHUIIconView::getIconColors()`, sorted.\n"
    body += "pub static COLORS: &[&str] = &[\n"
    body += "".join('    "%s",\n' % name for name in sorted(set(colors)))
    body += "];\n"
    write("icons.rs", "/// `PHUIIconView::getIcons()`, sorted.\n", body)


def config_keys():
    keys = set()
    for path in php_sources():
        with open(path, encoding="utf-8", errors="replace") as handle:
            keys.update(re.findall(r"newOption\(\s*'([^']+)'", handle.read()))
    write(
        "config_keys.rs",
        "/// The configuration options PHP defines (`newOption()`), sorted.\n",
        "pub static CONFIG_KEYS: &[&str] = &[\n"
        + "".join('    "%s",\n' % key for key in sorted(keys))
        + "];\n",
    )


def phid_types():
    types = set()
    for path in php_sources():
        if path.endswith("PHIDType.php"):
            with open(path, encoding="utf-8") as handle:
                types.update(re.findall(r"const TYPECONST = '([A-Z]{4})'", handle.read()))
    write(
        "phid_types.rs",
        "/// The PHID types PHP defines (`PhabricatorPHIDType::TYPECONST`), sorted.\n",
        "pub static PHID_TYPES: &[&str] = &[\n"
        + "".join('    "%s",\n' % phid_type for phid_type in sorted(types))
        + "];\n",
    )


os.makedirs(OUT, exist_ok=True)
emoji()
icons()
config_keys()
phid_types()
